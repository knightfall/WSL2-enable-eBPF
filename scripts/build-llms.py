#!/usr/bin/env python3
"""Generate the bounded documentation bundle, or check that it is current."""

import argparse
from pathlib import Path
import posixpath
import re
import sys
from urllib.parse import urlsplit, urlunsplit

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ('AGENTS.md', 'docs/REPOSITORY_MAP.md', 'README.md', 'KERNEL_CONFIG_EXPLAINED.md')
OUTPUT = ROOT / 'llms-full.txt'


def normalize_links(text, source):
    def replace(match):
        url = urlsplit(match[1])
        if url.scheme or url.netloc or not url.path or url.path.startswith('/'):
            return match[0]
        path = posixpath.normpath(posixpath.join(posixpath.dirname(source), url.path))
        return '](' + urlunsplit(('', '', path, url.query, url.fragment)) + ')'
    return re.sub(r'\]\(([^)]+)\)', replace, text)


def render():
    parts = [
        '# WSL2-enable-eBPF — complete project documentation\n\n'
        '> Generated by scripts/build-llms.py from a fixed first-party documentation allowlist.\n'
        '> This bundle excludes upstream kernel source, build artifacts, and local environment files.\n\n'
        'Use individual source pages or this bundle to avoid duplicate indexing. '
        'Regenerate after documentation changes; do not edit this file directly.\n'
    ]
    for source in SOURCES:
        body = normalize_links((ROOT / source).read_text(), source)
        parts.append(f'\n---\n\n## Source: {source}\n\n{body.rstrip()}\n')
    return ''.join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the committed bundle is missing or stale')
    args = parser.parse_args()
    contents = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != contents:
            sys.exit('llms-full.txt is stale or missing; run python3 scripts/build-llms.py')
        print('LLM documentation bundle is current.')
    else:
        OUTPUT.write_text(contents)
        print('Generated llms-full.txt from first-party documentation.')


if __name__ == '__main__':
    main()
